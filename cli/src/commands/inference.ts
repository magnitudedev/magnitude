import type { Command } from "@commander-js/extra-typings"

const loadRuntime = () => import("./inference-runtime")

const JSON_HELP = "Print one machine-readable JSON document"
const DRAFTER_HELP = "auto (the preselected drafter), none, built-in, a model ID, a Hugging Face reference, or a GGUF path"

export const registerInferenceCommands = (program: Command): void => {
  program.command("hardware")
    .description("Show hardware and memory available to local inference")
    .option("--json", JSON_HELP)
    .action((options) => loadRuntime().then(({ execute, showHardware }) => execute(showHardware(options))))

  const catalog = program.command("catalog").description("Find, compare, and download local models")
  catalog.command("status")
    .description("Show model catalog preparation and hardware assessment progress")
    .option("--json", JSON_HELP)
    .action((options) => loadRuntime().then(({ execute, showCatalogStatus }) => execute(showCatalogStatus(options))))
  catalog.command("list")
    .description("List catalog models compatible with this computer")
    .option("--json", JSON_HELP)
    .action((options) => loadRuntime().then(({ execute, showModelCatalog }) => execute(showModelCatalog(options))))
  catalog.command("show")
    .description("Show details for one catalog model")
    .argument("<model-id>", "Canonical model ID from `magnitude catalog list`")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, showCatalogModel }) => execute(showCatalogModel(modelId, options))))
  catalog.command("recommendations")
    .description("Rank compatible models for a speed-to-intelligence preference")
    .option("--preference <value>", "Fastest, Faster, Balanced, Smarter, or Smartest", "balanced")
    .option("--limit <count>", "Maximum recommendations to show", "10")
    .option("--json", JSON_HELP)
    .action((options) => loadRuntime().then(({ execute, showRecommendations }) =>
      execute(showRecommendations(options.preference, options.limit, options))))
  catalog.command("search")
    .description("Search Hugging Face for GGUF models that run in Magnitude")
    .argument("<query>", "Model name or words to search for")
    .option("--all", "Also list results Magnitude can't run, with the reason")
    .option("--limit <count>", "Maximum results to request, from 1 to 100")
    .option("--json", JSON_HELP)
    .action((query, options) => loadRuntime().then(({ execute, searchHuggingFace }) => execute(searchHuggingFace(query, options))))
  catalog.command("inspect")
    .description("Show a model's versions and drafters for this computer without changing anything")
    .argument("<reference>", "Hugging Face link, owner/repo, owner/repo:QUANT, or a GGUF path")
    .option("--json", JSON_HELP)
    .action((reference, options) => loadRuntime().then(({ execute, inspectCandidate }) => execute(inspectCandidate(reference, options))))
  catalog.command("pull")
    .description("Download or update a model, or add a model from Hugging Face")
    .argument("<model>", "Model ID, Hugging Face link, or owner/repo[:QUANT]")
    .option("--drafter <drafter>", DRAFTER_HELP)
    .option("--force", "Download a Hugging Face version that needs more memory than this computer can provide")
    .option("--only <component>", "Download only one missing component of a catalog model: projector (image input) or drafter")
    .option("--json", JSON_HELP)
    .action((model, options) => loadRuntime().then(({ execute, pullModel }) => execute(pullModel(model, options))))
  catalog.command("cancel")
    .description("Cancel an active model download or update")
    .argument("<model-id>", "Canonical model ID from `magnitude models status`")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, cancelDownload }) => execute(cancelDownload(modelId, options))))
  catalog.command("remove")
    .description("Remove a downloaded model from this computer")
    .argument("<model-id>", "Canonical model ID from `magnitude models status`")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, removeModel }) => execute(removeModel(modelId, options))))

  const models = program.command("models").description("Inspect and control local models on this computer")
  models.command("status")
    .description("Show local model installation and runtime status")
    .argument("[model-id]", "Canonical model ID from `magnitude models status`")
    .option("--all", "Also list models that can't run and hidden models")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, showModelsStatus }) =>
      execute(showModelsStatus(modelId, options))))
  models.command("load")
    .description("Load a local model for inference")
    .argument("<model-id>", "Canonical model ID from `magnitude models status`")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, loadInstance }) =>
      execute(loadInstance(modelId, options))))
  models.command("stop")
    .description("Stop the active local model")
    .option("--json", JSON_HELP)
    .action((options) => loadRuntime().then(({ execute, stopInstance }) => execute(stopInstance(options))))
  models.command("import")
    .description("Add one GGUF file where it is; Magnitude never moves or deletes it")
    .argument("<path>", "Path to a .gguf file")
    .option("--drafter <drafter>", DRAFTER_HELP)
    .option("--json", JSON_HELP)
    .action((path, options) => loadRuntime().then(({ execute, importModel }) => execute(importModel(path, options))))
  models.command("drafter")
    .description("Add, change, or turn off the drafter of a model that isn't from the catalog")
    .argument("<model-id>", "Canonical model ID from `magnitude models status`")
    .argument("<drafter>", DRAFTER_HELP)
    .option("--json", JSON_HELP)
    .action((modelId, drafter, options) => loadRuntime().then(({ execute, setModelDrafter }) =>
      execute(setModelDrafter(modelId, drafter, options))))
  models.command("hide")
    .description("Hide a model found on this computer; its files are untouched")
    .argument("<model-id>", "Canonical model ID from `magnitude models status`")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, hideModel }) => execute(hideModel(modelId, options))))
  models.command("unhide")
    .description("Show a hidden model again")
    .argument("<model-id>", "Canonical model ID from `magnitude models status --all`")
    .option("--json", JSON_HELP)
    .action((modelId, options) => loadRuntime().then(({ execute, unhideModel }) => execute(unhideModel(modelId, options))))

  const folders = models.command("folders").description("Manage where Magnitude looks for GGUF files")
  folders.command("list")
    .description("List automatic model locations and your folders")
    .option("--json", JSON_HELP)
    .action((options) => loadRuntime().then(({ execute, listModelLocations }) => execute(listModelLocations(options))))
  folders.command("add")
    .description("Watch a folder for GGUF files")
    .argument("<path>", "Folder path")
    .option("--json", JSON_HELP)
    .action((path, options) => loadRuntime().then(({ execute, addModelFolder }) => execute(addModelFolder(path, options))))
  folders.command("remove")
    .description("Stop watching a folder; its files are untouched")
    .argument("<path>", "Folder path")
    .option("--json", JSON_HELP)
    .action((path, options) => loadRuntime().then(({ execute, removeModelFolder }) => execute(removeModelFolder(path, options))))
  folders.command("enable")
    .description("Scan an automatic location again")
    .argument("<location>", "huggingface-cache, lm-studio, llama-cpp, or ollama")
    .option("--json", JSON_HELP)
    .action((location, options) => loadRuntime().then(({ execute, setModelLocationEnabled }) => execute(setModelLocationEnabled(location, true, options))))
  folders.command("disable")
    .description("Stop scanning an automatic location; its files are untouched")
    .argument("<location>", "huggingface-cache, lm-studio, llama-cpp, or ollama")
    .option("--json", JSON_HELP)
    .action((location, options) => loadRuntime().then(({ execute, setModelLocationEnabled }) => execute(setModelLocationEnabled(location, false, options))))
}
