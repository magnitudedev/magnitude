//! Single-owner speculative round pricing for both assessment (`estimate_execution`,
//! `streamed_estimates`) and runtime (`LaunchPrices` -> `draft_control.rs`).
//!
//! A speculative round generates `g` proposals in a drafter launch `D(g)` and
//! verifies `v` of them (`1 <= v <= g`) alongside their anchor in a target
//! launch `V(v + 1)`:
//!
//! ```text
//! tok_s(g, v) = E[a(v) + 1] / (D(g) + V(v + 1) + h(g, v))
//! rate        = max(1 / V_plain(1), max_{(g, v) in ladder} tok_s(g, v))
//! ```
//!
//! Both `D(g)` and `V(v + 1)` are unpipelined (`lookahead: false`), paying
//! `step_round_trip` each (`h(g, v)`), while plain decode `V_plain(1)` pays
//! the load's actual `lookahead` step cost. Expected committed tokens follow
//! the structural conditional stand-rate prior `sigma_prior(method, j)`:
//!
//! ```text
//! E[a(v) + 1] = 1 + sum_{j=1..=v} prod_{i=1..=j} sigma_i
//! ```

use crate::census::Census;
use crate::compute::launch_terms;
use crate::launch::TargetCensus;
use crate::lines::ReadLine;
use crate::streamed::{HeldSlots, StreamedLayers};
use seismic_measure::pricing::{Figures, PriceError, Pricing};

/// Structural class of a speculative drafter, governing both its execution
/// shape and its uncalibrated conditional stand-rate prior [`sigma_prior`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DraftMethod {
    /// Autoregressive chained head (MTP / target-reading MTP): `g` sequential
    /// steps of 1 row per sequence.
    Mtp,
    /// Parallel block drafter (DFlash / DFlash2 / DSpark / LiLiCorr): one
    /// block pass of `rows_per_sequence` rows per sequence producing `g`
    /// proposals.
    Block,
}

/// One candidate draft width `g` in a drafter's census: its proposing launch
/// census and the rows per sequence that launch executes.
#[derive(Clone, Debug, PartialEq)]
pub struct DraftWidthCensus {
    /// Number of proposals `g` generated by this launch (`g >= 1`).
    pub proposals: u8,
    /// Rows per sequence executed by the proposing launch (1 for chained MTP
    /// steps where `census` already unrolls `g` steps; `block_rows` for block
    /// drafters).
    pub rows_per_sequence: u64,
    /// Census of the proposing launch for `proposals` proposals.
    pub census: Census,
}

/// Complete pricing census of a load's drafter: its structural method,
/// candidate widths (sorted ascending by `proposals`), and maximum proposals.
#[derive(Clone, Debug, PartialEq)]
pub struct DraftCensus {
    pub method: DraftMethod,
    /// Candidate widths on the ladder (ascending by `proposals`).
    pub widths: Vec<DraftWidthCensus>,
    /// Maximum proposals the method can generate/verify in one round.
    pub max_proposals: u8,
}

impl DraftCensus {
    /// Every width census held by this drafter (for `Rates::covers` and
    /// `ExecutorCosts::figures`).
    pub fn censuses(&self) -> Vec<&Census> {
        self.widths.iter().map(|w| &w.census).collect()
    }

    /// The certified width census for `generated` proposals: exact match if
    /// present, else the narrowest certified width `>= generated`, else the
    /// widest certified width.
    pub fn width(&self, generated: u8) -> Option<&DraftWidthCensus> {
        if generated == 0 || self.widths.is_empty() {
            return None;
        }
        self.widths
            .iter()
            .find(|w| w.proposals >= generated)
            .or_else(|| self.widths.last())
    }
}

/// Structural conditional stand-rate prior `sigma_prior(method, depth)` for
/// 1-indexed proposal depth `depth >= 1`: the prior probability that proposal
/// `depth` is accepted given proposals `1..depth` were accepted.
///
/// Purely structural by drafter class (no per-model constants):
/// - `Mtp`: 1-layer target-conditioned head chaining its own hidden states.
/// - `Block`: multi-layer block drafter attending to fused target features.
pub fn sigma_prior(method: DraftMethod, depth: usize) -> f64 {
    assert!(depth >= 1, "invariant violated: proposal depth is 1-indexed");
    let (base, decay): (f64, f64) = match method {
        DraftMethod::Mtp => (0.72, 0.85),
        DraftMethod::Block => (0.78, 0.90),
    };
    base * decay.powi((depth - 1) as i32)
}

/// Expected committed tokens `E[a(v) + 1] = 1 + sum_{j=1..=v} prod_{i=1..=j} sigma_i`
/// from conditional stand rates `sigmas` (0-indexed: `sigmas[0]` is `sigma_1`).
pub fn expected_tokens(sigmas: &[f64]) -> f64 {
    let mut survival = 1.0;
    let mut tokens = 1.0;
    for &sigma in sigmas {
        survival *= sigma.clamp(0.0, 1.0);
        tokens += survival;
    }
    tokens
}

/// Expected committed tokens `E[a(v) + 1]` under [`sigma_prior`] for `method`
/// verifying `verified` proposals.
pub fn prior_expected_tokens(method: DraftMethod, verified: usize) -> f64 {
    let mut survival = 1.0;
    let mut tokens = 1.0;
    for depth in 1..=verified {
        survival *= sigma_prior(method, depth);
        tokens += survival;
    }
    tokens
}

/// Outcome of pricing speculative decode against plain decode at one depth.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SpeculativeRate {
    /// Best tokens per second per sequence: `max(plain_tokens_per_second, best_draft_tok_s)`.
    pub tokens_per_second: f64,
    /// Plain decode tokens per second (`1 / V_plain(1)`).
    pub plain_tokens_per_second: f64,
    /// Best `(generated, verified)` pair if drafting beats plain decode;
    /// `None` if plain decode wins.
    pub best_pair: Option<(u8, u8)>,
}

/// Single-owner speculative round pricer.
pub struct SpeculativePrice;

impl SpeculativePrice {
    /// Price a single drafter launch of `width` for `sequences` sequences at
    /// `depth` tokens, unpipelined (`lookahead: false`, paying one
    /// `step_round_trip`).
    pub fn draft_launch(
        width: &DraftWidthCensus,
        figures: &Figures,
        sequences: u64,
        depth: u32,
    ) -> Result<f64, PriceError> {
        let pricing = Pricing { figures, lookahead: false };
        Ok(launch_terms(
            &width.census,
            &pricing,
            sequences,
            sequences * width.rows_per_sequence,
            depth,
        )?
        .total())
    }

    /// Single-owner pricing loop over `(g, v)` on the ladder against plain
    /// decode.
    ///
    /// `target_seconds(rows, lookahead)` returns the target launch wall-clock
    /// seconds for `rows` total rows of `sequences` sequences under `lookahead`
    /// (`plain_lookahead` for plain decode, `false` for unpipelined verify).
    pub fn price_with(
        draft: &DraftCensus,
        figures: &Figures,
        sequences: u64,
        depth: u32,
        plain_lookahead: bool,
        mut target_seconds: impl FnMut(u64, bool) -> Result<f64, PriceError>,
    ) -> Result<SpeculativeRate, PriceError> {
        let plain_seconds = target_seconds(sequences, plain_lookahead)?;
        let plain_tok_s = 1.0 / plain_seconds;
        let mut best_tok_s = plain_tok_s;
        let mut best_pair = None;

        for width in &draft.widths {
            let g = width.proposals;
            if g == 0 {
                continue;
            }
            let d_g = Self::draft_launch(width, figures, sequences, depth)?;
            for v in 1..=g {
                if !((usize::from(v) + 1).is_power_of_two() || v == g) {
                    continue;
                }
                let verify_rows = sequences * (u64::from(v) + 1);
                let v_seconds = target_seconds(verify_rows, false)?;
                let round_seconds = d_g + v_seconds;
                let tok_s = prior_expected_tokens(draft.method, usize::from(v)) / round_seconds;
                if tok_s > best_tok_s {
                    best_tok_s = tok_s;
                    best_pair = Some((g, v));
                }
            }
        }

        Ok(SpeculativeRate {
            tokens_per_second: best_tok_s,
            plain_tokens_per_second: plain_tok_s,
            best_pair,
        })
    }

    /// Price a resident target with `draft` at `sequences` sequences and
    /// `depth` tokens.
    pub fn resident(
        target: &Census,
        draft: &DraftCensus,
        pricing: &Pricing<'_>,
        sequences: u64,
        depth: u32,
    ) -> Result<SpeculativeRate, PriceError> {
        target.decode_step(sequences)?;
        Self::price_with(
            draft,
            pricing.figures,
            sequences,
            depth,
            pricing.lookahead,
            |rows, lookahead| {
                let p = Pricing { figures: pricing.figures, lookahead };
                Ok(launch_terms(target, &p, sequences, rows, depth)?.total())
            },
        )
    }

    /// Price a streamed target with `draft` holding `held` slots at `sequences`
    /// sequences and `depth` tokens.
    #[allow(clippy::too_many_arguments)]
    pub fn streamed(
        target: &TargetCensus,
        draft: &DraftCensus,
        pricing: &Pricing<'_>,
        layers: &StreamedLayers,
        read: ReadLine,
        held: HeldSlots,
        sequences: u64,
        depth: u32,
    ) -> Result<SpeculativeRate, PriceError> {
        Self::price_with(
            draft,
            pricing.figures,
            sequences,
            depth,
            pricing.lookahead,
            |rows, lookahead| {
                let p = Pricing { figures: pricing.figures, lookahead };
                let compute = target.each(|census| launch_terms(census, &p, sequences, rows, depth))?;
                Ok(layers.step_seconds(None, read, held, rows as f64, compute).total_seconds)
            },
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::census::{Kind, LaunchCounts};
    use crate::launch::LaunchPrices;
    use seismic_measure::pricing::{Bytes, Flops, Format, HistoryFigure, HistoryLadder, Layout, Rates, Storage, Work};

    const BF16: Format = Format("bf16");
    const Q4K: Format = Format("q4k");
    const DENSE: Layout = Layout("dense");

    fn test_figures() -> Figures {
        let rates = Rates {
            activation: BF16,
            weights: Storage::ALL
                .iter()
                .flat_map(|&storage| [(storage, BF16, 300e9), (storage, Q4K, 300e9)])
                .collect(),
            flops: vec![(BF16, 60e12), (Q4K, 60e12)],
            history: vec![(
                DENSE,
                Ok(HistoryFigure {
                    ladder: HistoryLadder::new(1024, [(1024, 10e-6), (4096, 30e-6)]),
                    along: 300e9,
                    slowdown: 1.0,
                }),
            )],
            launch: 5e-6,
            decode: None,
        };
        Figures {
            rates,
            composition: Ok(1.0),
            step_pipelined: 50e-6,
            step_round_trip: 200e-6,
        }
    }

    fn single_weight_census(bytes: u64, flops: u64) -> Census {
        let launches = LaunchCounts::new((1..=8).map(|_| Ok(1)).collect());
        let work = Work {
            weights: vec![Bytes { format: Q4K, bytes }],
            row_flops: vec![Flops { format: Q4K, flops }],
            ..Work::default()
        };
        Census::new(vec![(Kind { work, launches }, None)], 0, 8)
    }

    /// A fast block drafter (e.g. DFlash) paired with a large target beats
    /// plain 1-row decode significantly: `E[a+1] / (D + V + h) > 1 / V_plain(1)`.
    #[test]
    fn fast_block_drafter_beats_plain_decode() {
        let figures = test_figures();
        // ~9 GB target => ~30 ms plain step (~33 tok/s), bandwidth-bound at 1..8 rows.
        let target = single_weight_census(9_000_000_000, 18_000_000_000);
        // ~0.9 GB block drafter => ~3 ms draft launch.
        let draft_w = single_weight_census(900_000_000, 1_800_000_000);
        let draft = DraftCensus {
            method: DraftMethod::Block,
            widths: vec![
                DraftWidthCensus { proposals: 1, rows_per_sequence: 2, census: draft_w.clone() },
                DraftWidthCensus { proposals: 3, rows_per_sequence: 4, census: draft_w.clone() },
                DraftWidthCensus { proposals: 7, rows_per_sequence: 8, census: draft_w },
            ],
            max_proposals: 7,
        };
        let pricing = Pricing { figures: &figures, lookahead: true };
        let rate = SpeculativePrice::resident(&target, &draft, &pricing, 1, 1024).unwrap();
        assert!(
            rate.tokens_per_second > 2.0 * rate.plain_tokens_per_second,
            "expected >2x speedup, got {:.1} vs plain {:.1}",
            rate.tokens_per_second,
            rate.plain_tokens_per_second,
        );
        assert_eq!(rate.best_pair, Some((7, 7)));
    }

    /// When the drafter is too expensive to pay for itself, `SpeculativePrice`
    /// falls back cleanly to plain 1-row decode (`best_pair == None`).
    #[test]
    fn expensive_drafter_falls_back_to_plain_decode() {
        let figures = test_figures();
        // Small target (~100 MB => 0.33 ms), huge drafter (~1 GB => 3.3 ms).
        let target = single_weight_census(100_000_000, 200_000_000);
        let draft_w = single_weight_census(1_000_000_000, 2_000_000_000);
        let draft = DraftCensus {
            method: DraftMethod::Mtp,
            widths: vec![
                DraftWidthCensus { proposals: 1, rows_per_sequence: 1, census: draft_w.clone() },
                DraftWidthCensus { proposals: 3, rows_per_sequence: 1, census: draft_w },
            ],
            max_proposals: 3,
        };
        let pricing = Pricing { figures: &figures, lookahead: true };
        let rate = SpeculativePrice::resident(&target, &draft, &pricing, 1, 1024).unwrap();
        assert_eq!(rate.best_pair, None);
        assert_eq!(rate.tokens_per_second, rate.plain_tokens_per_second);
    }

    /// `LaunchPrices::with_draft` supplies `draft_seconds`, `verify_seconds`,
    /// and `plain_seconds` agreeing bit-for-bit with `SpeculativePrice`.
    #[test]
    fn launch_prices_agrees_with_speculative_price() {
        let figures = test_figures();
        let target = single_weight_census(6_000_000_000, 12_000_000_000);
        let draft_w = single_weight_census(600_000_000, 1_200_000_000);
        let draft = DraftCensus {
            method: DraftMethod::Block,
            widths: vec![DraftWidthCensus { proposals: 7, rows_per_sequence: 8, census: draft_w }],
            max_proposals: 7,
        };
        let pricing = Pricing { figures: &figures, lookahead: true };
        let spec = SpeculativePrice::resident(&target, &draft, &pricing, 1, 1024).unwrap();
        let prices = LaunchPrices::with_draft(TargetCensus::Resident(target), Some(draft), figures, true);

        let d7 = prices.draft_seconds(1, 7, 1024).unwrap().unwrap();
        let v8 = prices.verify_seconds(1, 8, 1024).unwrap().resident;
        let plain = prices.plain_seconds(1, 1024).unwrap().resident;

        let expected_rate = prior_expected_tokens(DraftMethod::Block, 7) / (d7 + v8);
        assert!((spec.tokens_per_second - expected_rate).abs() < 1e-12);
        assert!((spec.plain_tokens_per_second - 1.0 / plain).abs() < 1e-12);
        // Verify unpipelined round trip > pipelined lookahead step.
        let v1_unpipelined = prices.verify_seconds(1, 1, 1024).unwrap().resident;
        assert!(v1_unpipelined > plain);
    }
}
